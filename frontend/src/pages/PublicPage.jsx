export default function PublicPage({ page }) {
  const [settings, setSettings] = useState(null),
    [demo, setDemo] = useState(null),
    [choice, setChoice] = useState(null),
    [result, setResult] = useState(null),
    [error, setError] = useState(""),
    [busy, setBusy] = useState(false),
    [pkg, setPkg] = useState(null);
  useEffect(() => {
    setError("");
    setResult(null);
    setChoice(null);
    if (page === "contact")
      api
        .get("/public/settings")
        .then((r) => setSettings(r.data))
        .catch((e) => setError(errorText(e)));
    if (page === "demo")
      api
        .get("/public/demo")
        .then((r) => setDemo(r.data))
        .catch((e) => setError(errorText(e)));
    if (page === "pricing")
      api
        .get("/public/package")
        .then((r) => setPkg(r.data))
        .catch((e) => setError(errorText(e)));
  }, [page]);
  async function submit(e) {
    e.preventDefault();
    setBusy(true);
    try {
      setResult((await api.post("/public/demo", { option: choice })).data);
    } catch (e) {
      setError(errorText(e));
    } finally {
      setBusy(false);
    }
  }
  return (
    <main id="main" className="shell page prose">
      <Notice error={error} />
      {content[page] && (
        <>
          <h1>{content[page][0]}</h1>
          {content[page].slice(1).map((p, i) => (
            <p key={i}>{p}</p>
          ))}
        </>
      )}
      {page === "contact" && (
        <>
          <h1>தொடர்பு</h1>
          <p>கணக்கு, கட்டணம் அல்லது தேர்வு தொடர்பான உதவிக்கு:</p>
          {settings?.contactEmail ? (
            <a href={`mailto:${settings.contactEmail}`}>
              {settings.contactEmail}
            </a>
          ) : (
            <p>
              ஆதரவு மின்னஞ்சல் இன்னும் அமைக்கப்படவில்லை. கட்டண வெளியீட்டிற்கு
              முன் அது சேர்க்கப்படும்.
            </p>
          )}
        </>
      )}
      {page === "pricing" && (
        <>
          <h1>அறிமுகத் தேர்வுத் தொகுப்பு</h1>
          {pkg ? (
            <>
              <p className="price">LKR {pkg.price}</p>
              <p>
                {pkg.examCount} தேர்வுகள் · ஒவ்வொன்றிலும் {pkg.questionsPerExam}{" "}
                வினாக்கள் · {pkg.durationMinutes} நிமிடங்கள்
              </p>
              <p>டிஜிட்டல் பாராட்டுப் பதக்கங்கள்; பணப் பரிசுகள் இல்லை.</p>
              <Link className="button" to="/payments">
                {pkg.purchasesEnabled
                  ? "கட்டண விவரம்"
                  : "தொகுப்பு நிலை பார்க்க"}
              </Link>
            </>
          ) : (
            <p>ஏற்றப்படுகிறது…</p>
          )}
        </>
      )}
      {page === "demo" && (
        <>
          <h1>இலவச மாதிரி வினா</h1>
          <p>
            பதிவு அல்லது கட்டணம் தேவையில்லை. இது முழுத் தேர்வு அல்ல;
            பயன்படுத்திப் பார்க்க ஒரு வினா.
          </p>
          {demo && (
            <form className="panel" onSubmit={submit}>
              <fieldset disabled={!!result || busy}>
                <legend className="question">{demo.question}</legend>
                {demo.options.map((o, i) => (
                  <label key={i} className="answer">
                    <input
                      type="radio"
                      checked={choice === i}
                      onChange={() => setChoice(i)}
                      name="demo"
                      required
                    />
                    {o}
                  </label>
                ))}
              </fieldset>
              <button
                className="button"
                disabled={choice === null || !!result || busy}
              >
                விடையைச் சரிபார்
              </button>
              {result && (
                <p className="explanation" role="status">
                  {result.correct
                    ? "சரியான விடை!"
                    : "மீண்டும் பயிற்சி செய்வோம்!"}{" "}
                  {result.explanation}
                </p>
              )}
            </form>
          )}
        </>
      )}
    </main>
  );
}
